// Writes lib/google-allowlist.generated.ts from public.google_allowlist
// (status = 'approved'). Every page NOT in that list gets
// "X-Robots-Tag: googlebot: noindex" from middleware.ts — Google only; Bing and
// other engines ignore googlebot-scoped directives. An empty list switches the
// feature off. Rebuild + deploy after changing approvals.
//
// Run: node --env-file=.env.local scripts/build-google-allowlist.mjs
import { writeFileSync } from "node:fs";

const BASE = (process.env.NEXT_PUBLIC_SUPABASE_URL || "").replace(/\/$/, "");
const KEY = process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.SUPABASE_SERVICE_KEY;
if (!BASE || !KEY) throw new Error("Missing Supabase env");

let rows = [];
for (let o = 0; ; o += 1000) {
  const r = await fetch(`${BASE}/rest/v1/google_allowlist?select=path&status=eq.approved&order=path&offset=${o}&limit=1000`, {
    headers: { Authorization: `Bearer ${KEY}`, apikey: KEY },
  });
  if (!r.ok) throw new Error(`google_allowlist ${r.status}: ${await r.text()}`);
  const page = await r.json();
  rows = rows.concat(page);
  if (page.length < 1000) break;
}

// Stored decoded ("/artworks/vorfrühling"); middleware decodes the request path the same way.
const paths = [...new Set(rows.map((r) => decodeURI(r.path).replace(/\/+$/, "") || "/"))].sort();
const body = `// GENERATED by scripts/build-google-allowlist.mjs on ${new Date().toISOString().slice(0, 10)} — do not edit.
// Pages Google may index (${paths.length}). Empty = feature off. See middleware.ts.
export const GOOGLE_ALLOWLIST: ReadonlySet<string> = new Set<string>([${paths.map((p) => `\n  ${JSON.stringify(p)},`).join("")}${paths.length ? "\n" : ""}]);
`;
writeFileSync(new URL("../lib/google-allowlist.generated.ts", import.meta.url), body);
console.log(`lib/google-allowlist.generated.ts: ${paths.length} paths`);
